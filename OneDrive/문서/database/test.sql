CREATE TABLE BANK
(CODE CHAR(5),
NAME VARCHAR(20),
ADDRESS VARCHAR(20),
PRIMARY KEY(CODE));
CREATE TABLE CUSTOMER
( CNO NUMBER(2),
NAME VARCHAR(20),
AGE NUMBER(2),
ADDRESS VARCHAR(20),
PRIMARY KEY(CNO));
CREATE TABLE ACCOUNT
( ACNO NUMBER(4),
CNO NUMBER(2),
TYPE VARCHAR(10),
BALANCE NUMBER(5),
BANKCODE CHAR(5),
PRIMARY KEY(ACNO,CNO),
FOREIGN KEY(CNO) REFERENCES CUSTOMER(CNO),
FOREIGN KEY(BANKCODE) REFERENCES BANK(CODE));
CREATE TABLE LOAN
( LNO NUMBER(4),
CNO NUMBER(2),
TYPE VARCHAR(10),
AMT NUMBER(5),
BANKCODE CHAR(5),
PRIMARY KEY(LNO,CNO),
FOREIGN KEY(CNO) REFERENCES CUSTOMER(CNO),
FOREIGN KEY(BANKCODE) REFERENCES BANK(CODE));